"""Скидання Working Memory — голосові команди для зміни теми.

Тригери:
  • "забудь контекст" / "забудь розмову" — м'яке скидання (тема + сутності)
  • "нова тема" / "почнемо спочатку"     — м'яке скидання
  • "повністю забудь" / "стерти пам'ять розмови" — жорстке (включно з турнами)

Не чіпає довгострокову пам'ять (RAG, KG, SQLite-факти).
"""
from __future__ import annotations

import logging

logger = logging.getLogger(__name__)

TRIGGERS = [
    "забудь контекст",
    "забудь розмову",
    "нова тема",
    "почнемо спочатку",
    "повністю забудь",
    "стерти пам'ять розмови",
    "стерти память розмови",
    "що в робочій пам'яті",
    "що в робочій памяті",
    "покажи робочу пам'ять",
    "покажи робочу память",
]

_HARD = ("повністю забудь", "стерти пам'ять розмови", "стерти память розмови")
_SHOW = ("що в робочій пам'яті", "що в робочій памяті", "покажи робочу пам'ять", "покажи робочу память")


def execute(cmd, jarvis):
    wm = getattr(jarvis, "working_memory", None)
    if wm is None:
        return "Робоча пам'ять недоступна."

    cmd_l = cmd.lower()

    # Перегляд стану
    if any(t in cmd_l for t in _SHOW):
        s = wm.stats()
        ents = wm.context_block(max_chars=400) or "(порожньо)"
        return (
            f"Робоча пам'ять:\n"
            f"  • реплік: {s['turns']}\n"
            f"  • активних сутностей: {s['entities']}\n"
            f"  • тема: {s['topic'] or '—'}\n"
            f"  • остання дія: {s['last_skill'] or '—'}\n"
            f"  • незавершених цілей: {s['pending_goals']}\n"
            f"\n{ents}"
        )

    hard = any(t in cmd_l for t in _HARD)
    wm.clear(hard=hard)
    return "Готово, повністю очищено робочу пам'ять." if hard else "Гаразд, починаємо нову тему."
